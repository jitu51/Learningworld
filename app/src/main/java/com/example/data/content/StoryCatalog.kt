    private fun buildStory(
        id: String,
        title: String,
        heroName: String,
        heroEmoji: String,
        summary: String,
        vocabA: Pair<String, String>,
        vocabB: Pair<String, String>,
        scene1: String,
        choice1A: String,
        choice1B: String,
        branchA: String,
        branchB: String,
        question: String,
        options: List<String>,
        answer: String,
        moral: String
    ): InteractiveStory {
        return InteractiveStory(
            id = id,
            title = title,
            heroName = heroName,
            heroEmoji = heroEmoji,
            summary = summary,
            startNodeId = "start",
            nodes = mapOf(
                "start" to StoryNode(
                    id = "start",
                    sceneEmoji = heroEmoji,
                    title = title,
                    narration = scene1,
                    vocabularyWord = vocabA.first,
                    vocabularyMeaning = vocabA.second,
                    choices = listOf(
                        StoryChoice(text = choice1A, nextNodeId = "branch_a", pointsBonus = 10),
                        StoryChoice(text = choice1B, nextNodeId = "branch_b", pointsBonus = 5)
                    )
                ),
                "branch_a" to StoryNode(
                    id = "branch_a",
                    sceneEmoji = "✨",
                    title = "Wise Choice!",
                    narration = branchA,
                    vocabularyWord = vocabB.first,
                    vocabularyMeaning = vocabB.second,
                    choices = listOf(StoryChoice(text = "Continue to Story Quiz", nextNodeId = "quiz", pointsBonus = 5))
                ),
                "branch_b" to StoryNode(
                    id = "branch_b",
                    sceneEmoji = "💡",
                    title = "Learning Moment!",
                    narration = branchB,
                    vocabularyWord = vocabB.first,
                    vocabularyMeaning = vocabB.second,
                    choices = listOf(StoryChoice(text = "Continue to Story Quiz", nextNodeId = "quiz", pointsBonus = 5))
                ),
                "quiz" to StoryNode(
                    id = "quiz",
